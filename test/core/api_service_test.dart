import 'dart:convert';
import 'dart:typed_data';

import 'package:flutter_test/flutter_test.dart';
import 'package:http/http.dart' as http;
import 'package:http/testing.dart';
import 'package:streakly_app/core/config/api_config.dart';
import 'package:streakly_app/core/network/api_service.dart';

const _demo = ApiConfig(mode: ApiMode.demo, aiBaseUrl: 'http://localhost:8000', demoUserId: 'demo-user');
const _backend = ApiConfig(
  mode: ApiMode.backend,
  backendBaseUrl: 'https://api.example.com/',
  devAuthToken: 'token-123',
  timezone: 'Africa/Cairo',
);

http.Response _json(Object body, [int status = 200]) =>
    http.Response(jsonEncode(body), status, headers: {'content-type': 'application/json'});

void main() {
  group('configuration', () {
    test('base URLs are configurable and backend calls carry the token', () async {
      late http.BaseRequest seen;
      final api = ApiService(
        config: _backend,
        client: MockClient((req) async {
          seen = req;
          return _json({'goals': []});
        }),
      );
      expect(await api.getGoals(), isEmpty);
      expect(seen.url.toString(), 'https://api.example.com/goals');
      expect(seen.headers['authorization'], 'Bearer token-123');
    });

    test('demo mode talks straight to dawem-ai, with the API key when one is set', () async {
      late http.BaseRequest seen;
      final api = ApiService(
        config: _demo.copyWith(aiApiKey: 'k', aiBaseUrl: 'http://10.0.2.2:8000'),
        client: MockClient((req) async {
          seen = req;
          return _json({'file_id': 'f1', 'chunk_count': 3});
        }),
      );
      final r = await api.indexNotes(fileId: 'f1', fileName: 'n', text: 't');
      expect(seen.url.toString(), 'http://10.0.2.2:8000/files/index-notes');
      expect(seen.headers['x-api-key'], 'k');
      expect(seen.headers.containsKey('authorization'), isFalse);
      expect(r.fileId, 'f1');
      expect(r.chunkCount, 3);
    });

    test('backend mode without API_BASE_URL fails with a clear message', () async {
      final api = ApiService(
        config: const ApiConfig(mode: ApiMode.backend),
        client: MockClient((_) async => _json({})),
      );
      expect(() => api.getGoals(), throwsA(isA<ApiException>().having((e) => e.code, 'code', 'not_configured')));
    });
  });

  group('demo mode: dawem-ai contract (snake_case on the wire)', () {
    test('plan request/response round trip, tasks scheduled from the goal start date', () async {
      late Map<String, dynamic> sent;
      final api = ApiService(
        config: _demo,
        client: MockClient((req) async {
          sent = jsonDecode(req.body) as Map<String, dynamic>;
          return _json({
            'plan_id': 'p1',
            'title': 'Plan',
            'tasks': [
              {
                'task_id': 't1', 'day_number': 2, 'title': 'Day two', 'description': 'd', 'kind': 'practice',
                'duration_minutes': 30,
                'sources': [
                  {'chunk_id': 'c', 'file_id': 'f1', 'file_name': 'a.pdf', 'page_number': 5},
                ],
              },
            ],
          });
        }),
      );
      final goal = await api.createGoal(
        title: 'Learn Python', durationDays: 3, dailyMinutes: 5, startDate: DateTime(2026, 11, 30));
      final plan = await api.generatePlan(goal: goal, fileIds: ['f1']);

      expect(sent['user_id'], 'demo-user');
      expect(sent['file_ids'], ['f1']);
      expect(sent['duration_days'], 3);
      expect(sent['daily_minutes'], 10); // dawem-ai minimum
      expect(sent['level'], 'beginner');
      expect(plan.planId, 'p1');
      expect(plan.tasks.single.date, '2026-12-01');
      expect(plan.tasks.single.goalId, goal.goalId);
      expect(plan.tasks.single.sourceRefs, ['a.pdf, p. 5']);
    });

    test('multipart upload sends user_id, file_id, file_name and the file', () async {
      late http.BaseRequest seen;
      final api = ApiService(
        config: _demo,
        client: MockClient.streaming((req, body) async {
          seen = req;
          final bytes = await body.toBytes();
          expect(utf8.decode(bytes, allowMalformed: true), contains('hello'));
          return http.StreamedResponse(
            Stream.value(utf8.encode(jsonEncode({'file_id': 'f9', 'chunk_count': 1}))),
            200,
            headers: {'content-type': 'application/json'},
          );
        }),
      );
      final r = await api.indexFile(fileId: 'f9', fileName: 'notes.txt', bytes: Uint8List.fromList(utf8.encode('hello')));
      final fields = (seen as http.MultipartRequest).fields;
      expect(fields, {'user_id': 'demo-user', 'file_id': 'f9', 'file_name': 'notes.txt'});
      expect(r.fileId, 'f9');
      expect((await api.listFiles()).single.fileName, 'notes.txt');
    });

    test('quiz generated by dawem-ai is graded on the device', () async {
      final api = ApiService(
        config: _demo,
        client: MockClient((_) async => _json({
              'quiz_id': 'q1',
              'title': 'Quiz',
              'mcqs': [
                {
                  'question_id': 'm1', 'question': 'Question one?', 'options': ['a', 'b', 'c', 'd'],
                  'correct_option_index': 1, 'explanation': 'because', 'difficulty': 'easy',
                  'sources': [
                    {'chunk_id': 'c', 'file_id': 'f', 'file_name': 'a.pdf'},
                  ],
                },
              ],
              'recall_questions': [],
            })),
      );
      final quiz = await api.generateQuiz(fileIds: ['f'], numMcqs: 1, numRecall: 0);
      final result = await api.submitQuiz(quiz, {'m1': 1});
      expect(result.score, 1);
      expect(result.percentage, 100);
    });
  });

  group('backend mode: camelCase contract', () {
    test('createGoal posts the goal shape the Lambda validates', () async {
      late Map<String, dynamic> sent;
      final api = ApiService(
        config: _backend,
        client: MockClient((req) async {
          sent = jsonDecode(req.body) as Map<String, dynamic>;
          return _json({'goalId': 'g1', 'status': 'PLAN_PENDING'}, 201);
        }),
      );
      final goal = await api.createGoal(
        title: 'Learn', durationDays: 7, dailyMinutes: 30, startDate: DateTime(2026, 11, 30), level: 'Beginner');
      expect(sent['startDate'], '2026-11-30');
      expect(sent['level'], 'beginner');
      expect(sent['durationDays'], 7);
      expect(goal.goalId, 'g1');
      expect(goal.status, 'PLAN_PENDING');
    });

    test('generatePlan against the backend', () async {
      late Map<String, dynamic> sent;
      late Uri url;
      final api = ApiService(
        config: _backend,
        client: MockClient((req) async {
          sent = jsonDecode(req.body) as Map<String, dynamic>;
          url = req.url;
          return _json({
            'goalId': 'g1', 'planId': 'p1', 'title': 'Plan', 'status': 'PLAN_READY',
            'tasks': [
              {
                'taskId': '2026-11-30-abcd1234', 'goalId': 'g1', 'dayNumber': 1, 'date': '2026-11-30',
                'title': 'Read', 'description': 'd', 'durationMinutes': 20, 'sourceRefs': [],
              },
            ],
          }, 201);
        }),
      );
      final goal = GoalModel(
        goalId: 'g1', title: 'x', description: 'd', durationDays: 1, dailyMinutes: 20, startDate: DateTime(2026, 11, 30));
      final plan = await api.generatePlan(goal: goal, fileIds: ['f1']);
      expect(url.path, '/plans/generate');
      expect(sent, {'goalId': 'g1', 'fileIds': ['f1']});
      expect(plan.planId, 'p1');
      expect(plan.tasks.single.taskId, '2026-11-30-abcd1234');
    });

    test('completeTask posts goalId as a query parameter', () async {
      late Uri url;
      final api = ApiService(
        config: _backend,
        client: MockClient((req) async {
          url = req.url;
          return _json({
            'taskId': 't', 'xpGained': 10, 'totalXP': 10, 'level': 1,
            'streak': {'currentStreak': 1, 'longestStreak': 1},
          });
        }),
      );
      final r = await api.completeTask(taskId: '2026-11-30-abcd1234', goalId: 'g1');
      expect(url.path, '/tasks/2026-11-30-abcd1234/complete');
      expect(url.queryParameters, {'goalId': 'g1'});
      expect(r.currentStreak, 1);
    });

    test('ensureProfile sends the configured timezone', () async {
      late Map<String, dynamic> sent;
      late String method;
      final api = ApiService(
        config: _backend,
        client: MockClient((req) async {
          sent = jsonDecode(req.body) as Map<String, dynamic>;
          method = req.method;
          return _json({});
        }),
      );
      await api.ensureProfile(displayName: ' Sara ');
      expect(method, 'PUT');
      expect(sent, {'timezone': 'Africa/Cairo', 'displayName': 'Sara'});
    });

    test('quiz is submitted for server-side grading', () async {
      late Map<String, dynamic> sent;
      final api = ApiService(
        config: _backend,
        client: MockClient((req) async {
          sent = jsonDecode(req.body) as Map<String, dynamic>;
          return _json({
            'quizId': 'q1', 'resultId': 'r1', 'score': 1, 'total': 2, 'percentage': 50,
            'mcqResults': [
              {'questionId': 'm1', 'selectedOptionIndex': 1, 'correctOptionIndex': 1, 'isCorrect': true, 'explanation': 'e'},
            ],
            'recallReview': [],
          });
        }),
      );
      const quiz = QuizModel(quizId: 'q1', title: 'T', mcqs: []);
      final r = await api.submitQuiz(quiz, {'m1': 1}, recallAnswers: {'r1': 'x'});
      expect(sent['answers'], [{'questionId': 'm1', 'selectedOptionIndex': 1}]);
      expect(sent['recallAnswers'], [{'questionId': 'r1', 'answer': 'x'}]);
      expect(r.percentage, 50);
      expect(r.mcqResults.single.isCorrect, isTrue);
    });
  });

  group('errors', () {
    test('backend {error, code} body becomes an ApiException', () async {
      final api = ApiService(
        config: _backend,
        client: MockClient((_) async => _json({'error': 'This goal already has a plan', 'code': 'PLAN_EXISTS'}, 409)),
      );
      final goal = GoalModel(
        goalId: 'g1', title: 'x', description: 'd', durationDays: 1, dailyMinutes: 20, startDate: DateTime(2026, 11, 30));
      expect(
        () => api.generatePlan(goal: goal, fileIds: ['f']),
        throwsA(isA<ApiException>()
            .having((e) => e.statusCode, 'statusCode', 409)
            .having((e) => e.code, 'code', 'PLAN_EXISTS')
            .having((e) => e.message, 'message', 'This goal already has a plan')),
      );
    });

    test('dawem-ai {detail, code} body (422 insufficient_context) becomes an ApiException', () async {
      final api = ApiService(
        config: _demo,
        client: MockClient((_) async => _json({'code': 'insufficient_context', 'detail': 'Not enough material'}, 422)),
      );
      expect(
        () => api.generateQuiz(fileIds: ['f']),
        throwsA(isA<ApiException>()
            .having((e) => e.statusCode, 'statusCode', 422)
            .having((e) => e.code, 'code', 'insufficient_context')),
      );
    });

    test('network failures are reported with status 0', () async {
      final api = ApiService(
        config: _backend,
        client: MockClient((_) async => throw http.ClientException('connection refused')),
      );
      expect(() => api.getBadges(), throwsA(isA<ApiException>().having((e) => e.isNetworkError, 'isNetworkError', isTrue)));
    });
  });
}
